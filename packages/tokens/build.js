// @ts-check
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { formatHex } from 'culori';
import StyleDictionary from 'style-dictionary';

/** Everything resolves from this file, never from cwd — see `src` below. */
const HERE = dirname(fileURLToPath(import.meta.url));

/**
 * One declaration, or two for colours.
 *
 * @param {string} name
 * @param {string} value
 * @returns {string}
 */
function declare(name, value) {
  if (!value.startsWith('oklch(')) return `  --${name}: ${value};`;
  const hex = formatHex(value);
  if (hex === undefined) throw new Error(`Could not convert to hex: ${name} = ${value}`);
  // Hex first: a browser that cannot parse oklch keeps this line.
  return `  --${name}: ${hex};\n  --${name}: ${value};`;
}

/**
 * Resolve one theme to a flat token map.
 *
 * `getPlatformTokens` returns the resolved dictionary directly, so no custom
 * format and no throwaway file are needed. Paths are absolute because running
 * this from the repo root would otherwise match zero sources and silently emit
 * an empty stylesheet.
 *
 * @param {'light' | 'dark'} theme
 * @returns {Promise<Record<string, string>>}
 */
async function resolveTheme(theme) {
  const sd = new StyleDictionary({
    usesDtcg: true,
    source: [resolve(HERE, 'src/primitive/*.json'), resolve(HERE, `src/semantic/${theme}.json`)],
    platforms: { web: { transformGroup: 'css' } },
  });
  const dictionary = await sd.getPlatformTokens('web');

  /** @type {Record<string, string>} */
  const flat = {};
  for (const token of dictionary.allTokens) {
    flat[token.path.join('-')] = String(token.$value ?? token.value);
  }
  if (Object.keys(flat).length === 0) {
    throw new Error(`No tokens resolved for the ${theme} theme — check the source globs.`);
  }
  return flat;
}

const light = await resolveTheme('light');
const dark = await resolveTheme('dark');

/** Tokens identical across themes are declared once, in :root. */
const shared = Object.keys(light).filter((k) => light[k] === dark[k]);
const themed = Object.keys(light).filter((k) => light[k] !== dark[k]);

/**
 * @param {Record<string, string>} map
 * @param {string[]} keys
 * @returns {string}
 */
function block(map, keys) {
  return keys
    .map((k) => {
      const value = map[k];
      if (value === undefined) throw new Error(`Token ${k} has no value`);
      return declare(k, value);
    })
    .join('\n');
}

/*
 * `color-scheme` must be emitted here rather than hand-written in the app.
 * It is what tells the UA to render scrollbars, form controls, autofill and
 * the pre-paint canvas in the matching scheme — without it a dark theme keeps
 * light scrollbars and flashes white on load. It belongs with the theme that
 * sets it, so the two can never drift apart.
 */
const css = `/* Generated by build.js — do not edit. */
:root {
  color-scheme: light;
${block(light, shared)}
${block(light, themed)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${block(dark, themed)}
  }
}

:root[data-theme="dark"] {
  color-scheme: dark;
${block(dark, themed)}
}

/*
 * Alias the token families onto Tailwind's own namespaces, so \`font-sans\`,
 * \`font-mono\` and the spacing scale resolve to these tokens instead of
 * Tailwind's defaults. Without this they are two independent scales that agree
 * by coincidence and drift silently.
 */
@theme inline {
  --font-sans: var(--type-family-body);
  --font-mono: var(--type-family-data);
  --spacing: var(--space-1);
${[...shared, ...themed].map((k) => `  --${k}: var(--${k});`).join('\n')}
}
`;

/**
 * @param {Record<string, string>} map
 * @returns {Record<string, string>}
 */
const hexed = (map) =>
  Object.fromEntries(
    Object.entries(map).map(([k, v]) => [k, v.startsWith('oklch(') ? (formatHex(v) ?? v) : v]),
  );

const data = { light: hexed(light), dark: hexed(dark) };
const dist = resolve(HERE, 'dist');

await mkdir(dist, { recursive: true });
await writeFile(resolve(dist, 'tokens.css'), css, 'utf8');
await writeFile(
  resolve(dist, 'tokens.ts'),
  `// Generated by build.js — do not edit.\nexport const tokens = ${JSON.stringify(data, null, 2)} as const;\n\nexport type TokenName = keyof typeof tokens.light;\n`,
  'utf8',
);
await writeFile(resolve(dist, 'tokens.hex.json'), JSON.stringify(data, null, 2) + '\n', 'utf8');
