"""Unit tests for the declarative base, mixins and CHECK-constraint helper.

These assert on metadata only - no database is involved, which is the point: a
wrong column type should fail in milliseconds, not after a container starts.
"""

from __future__ import annotations

from datetime import UTC

from sqlalchemy import DateTime, Table

from beff.db.base import NAMING_CONVENTION, Base, sql_value_list, utcnow
from beff.modules.auth.models import RefreshToken, User
from beff.modules.onboarding.models import Line, OnboardingProgress, Plant
from beff.modules.privacy.models import ConsentRecord

ALL_MODELS: tuple[type[Base], ...] = (
    User,
    RefreshToken,
    OnboardingProgress,
    Plant,
    Line,
    ConsentRecord,
)


def table_of(model: type[Base]) -> Table:
    """`DeclarativeBase.__table__` is typed `FromClause`, which has no `indexes`.

    Every model here is mapped to a real `Table`, so narrowing once beats
    scattering casts through the assertions.
    """
    table = model.__table__
    assert isinstance(table, Table)
    return table


def test_utcnow_is_timezone_aware_and_utc() -> None:
    now = utcnow()

    assert now.tzinfo is not None
    assert now.utcoffset() == UTC.utcoffset(None)


def test_sql_value_list_renders_a_check_friendly_literal_list() -> None:
    assert sql_value_list(("member", "admin")) == "('member', 'admin')"


def test_sql_value_list_does_not_emit_a_trailing_comma_for_one_value() -> None:
    """`str(("only",))` would produce `('only',)`, which PostgreSQL rejects."""
    assert sql_value_list(("only",)) == "('only')"


def test_naming_convention_covers_every_constraint_kind() -> None:
    """A convention with a gap leaves autogenerated names a downgrade cannot drop."""
    assert set(NAMING_CONVENTION) == {"ix", "uq", "ck", "fk", "pk"}


def test_every_datetime_column_declares_a_timezone() -> None:
    for model in ALL_MODELS:
        for column in table_of(model).columns:
            if isinstance(column.type, DateTime):
                assert column.type.timezone is True, f"{model.__tablename__}.{column.name}"


def test_no_column_uses_a_length_limited_string_type() -> None:
    """`TEXT` always. A `length` on the type means somebody wrote `VARCHAR(n)`."""
    for model in ALL_MODELS:
        for column in table_of(model).columns:
            assert getattr(column.type, "length", None) is None, (
                f"{model.__tablename__}.{column.name}"
            )


def test_no_column_uses_a_postgresql_enum_type() -> None:
    for model in ALL_MODELS:
        for column in table_of(model).columns:
            assert type(column.type).__name__ not in {"Enum", "ENUM"}


def test_exposed_tables_use_uuid_keys_and_internal_tables_use_bigint() -> None:
    """ADR-0010's rule, asserted rather than trusted to review."""
    assert type(table_of(User).c.id.type).__name__ == "Uuid"

    for model in (RefreshToken, OnboardingProgress, Plant, Line, ConsentRecord):
        assert type(table_of(model).c.id.type).__name__ == "BigInteger", model.__tablename__
        assert table_of(model).c.id.identity is not None, model.__tablename__


def test_users_email_uniqueness_is_partial_on_deleted_at() -> None:
    """A plain UNIQUE would keep an erased address hostage forever."""
    index = next(i for i in table_of(User).indexes if i.name == "uq_users_email_active")

    assert index.unique is True
    assert "deleted_at IS NULL" in str(index.dialect_options["postgresql"]["where"])


def test_refresh_tokens_index_both_the_foreign_key_and_the_family() -> None:
    names = {index.name for index in table_of(RefreshToken).indexes}

    assert "ix_refresh_tokens_user_id" in names
    assert "ix_refresh_tokens_family_id" in names


def test_consent_records_have_no_updatable_state_column() -> None:
    """The log records events. There is no current-state column to mutate."""
    columns = set(table_of(ConsentRecord).columns.keys())

    assert "granted" in columns
    assert "withdrawn" not in columns
    assert "is_active" not in columns
