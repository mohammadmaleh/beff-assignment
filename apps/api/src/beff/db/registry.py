"""The one place every model is imported.

Alembic's `env.py` and `Base.metadata.create_all` only know about tables whose
model modules have been imported. Domain modules are imported lazily by the app,
so without this registry an autogenerated migration would quietly drop every
table it had not seen — the classic "alembic wants to delete my schema" bug.

Imports here are deliberately unused; `__all__` documents that, and the noqa
keeps ruff from removing them.
"""

from __future__ import annotations

from sqlalchemy import MetaData

from beff.db.base import Base
from beff.modules.auth.models import RefreshToken, User
from beff.modules.onboarding.models import Line, OnboardingProgress, Plant
from beff.modules.privacy.models import ConsentRecord

__all__ = [
    "ConsentRecord",
    "Line",
    "OnboardingProgress",
    "Plant",
    "RefreshToken",
    "User",
    "target_metadata",
]

target_metadata: MetaData = Base.metadata
